const expected='17a25dd92cedb0d2ec0a9a74fb194493f9c3bd79eb415ba12071e8beb04476e2';
const r=await fetch(url,{cache:'no-store'});
if(!r.ok) throw new Error('R25 download failed: '+r.status);
const b=Buffer.from(await r.arrayBuffer());
const got=crypto.createHash('sha256').update(b).digest('hex');
if(got!==expected) throw new Error('R25 checksum mismatch: '+got);
await fs.rm('public',{recursive:true,force:true});
await fs.mkdir('public',{recursive:true});
await fs.writeFile('public/index.html',b);
await fs.writeFile('public/build.txt','TOVATI R25 '+got+'\n');
